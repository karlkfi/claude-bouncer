class CategoryTests(unittest.TestCase):
    def test_each_builder(self):
        self.assertEqual(fr.category_of(REASON_WATCH), "watch")
        self.assertEqual(fr.category_of(REASON_LOOP), "loop-sleep")
        self.assertEqual(fr.category_of(REASON_SANDWICH), "sandwich")
        self.assertEqual(fr.category_of(REASON_SLEEP), "bare-sleep")
        self.assertEqual(fr.category_of(REASON_SLOW), "slow-timeout")
        self.assertEqual(fr.category_of(REASON_SLOW_TARGET), "slow-timeout")

    def test_backgrounded_class_a_keeps_its_category(self):
        # A poll run with run_in_background: true still prompts (issue #15),
        # with reworded reasons that must bucket the same way.
        self.assertEqual(fr.category_of(REASON_BG_WATCH), "watch")
        self.assertEqual(fr.category_of(REASON_BG_LOOP), "loop-sleep")
        self.assertEqual(fr.category_of(REASON_BG_SANDWICH), "sandwich")
        self.assertEqual(fr.category_of(REASON_BG_SLEEP), "bare-sleep")

    def test_signatures_mutually_exclusive(self):
        # No fixture reason matches more than one category signature.
        reasons = [REASON_WATCH, REASON_LOOP, REASON_SANDWICH, REASON_SLEEP,
                   REASON_SLOW, REASON_SLOW_TARGET, REASON_BG_WATCH,
                   REASON_BG_LOOP, REASON_BG_SANDWICH, REASON_BG_SLEEP]
        for reason in reasons:
            hits = [c for c, rx in fr.CATEGORY_PATTERNS.items()
                    if rx.search(reason)]
            self.assertEqual(len(hits), 1, "%r matched %s" % (reason, hits))

    def test_every_category_has_a_hint(self):
        for cat in fr.CATEGORY_PATTERNS:
            self.assertIn(cat, fr.CATEGORY_HINT)

    def test_unmatched_is_other(self):
        self.assertEqual(fr.category_of("foreground-guard: something new"),
                         "other")

    def test_override_keeps_underlying_category(self):
        # The override prefix does not change the underlying category.
        self.assertEqual(fr.category_of(REASON_OVERRIDE), "watch")


