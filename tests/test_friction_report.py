class EndToEndTests(unittest.TestCase):
    def _run(self, root, *args):
        r = subprocess.run(
            [sys.executable, str(SCRIPT), "--transcripts", root,
             "--since", "all", *args],
            capture_output=True, text=True, timeout=30)
        self.assertEqual(r.returncode, 0, r.stderr)
        return r.stdout

    def test_text_report(self):
        use, att = _decision_record(
            "toolu_1", "gh run watch 456", _stdout("ask", REASON_WATCH))
        root = write_transcript([use, att])
        out = self._run(root)
        self.assertIn("foreground-guard decisions recorded: 1", out)
        self.assertIn("watch", out)
        self.assertIn("gh run watch 456", out)

    def test_json_report(self):
        use, att = _decision_record(
            "toolu_1", "make test-race", _stdout("ask", REASON_SLOW))
        root = write_transcript([use, att])
        out = self._run(root, "--json")
        data = json.loads(out)
        self.assertEqual(data["total"], 1)
        self.assertEqual(data["decisions"]["ask"], 1)
        self.assertEqual(data["categories"]["slow-timeout"], 1)
        self.assertEqual(data["tools"]["make"], 1)

    def test_sibling_override_never_reported_as_ours(self):
        use1, att1 = _decision_record(
            "toolu_1", "gh run watch 456", _stdout("ask", REASON_WATCH))
        use2, att2 = _decision_record(
            "toolu_2", "kubectl delete ns x",
            _stdout("ask", REASON_SIBLING_OVERRIDE),
            hook_cmd='python3 "/x/bash-prod-guard.py"')
        root = write_transcript([use1, att1, use2, att2])

        # This guard's own report: the sibling's override is not ours.
        self.assertEqual(json.loads(self._run(root, "--json"))["overrides"], 0)

        # --plugin all: both decisions in scope, no override count at all.
        data = json.loads(self._run(root, "--plugin", "all", "--json"))
        self.assertEqual(data["total"], 2)
        self.assertNotIn("overrides", data)
        out = self._run(root, "--plugin", "all")
        self.assertIn("guard decisions recorded: 2", out)
        self.assertNotIn("FOREGROUND_GUARD_OVERRIDE", out)

    def test_denying_guard_reports_its_friction(self):
        # An unattended-mode session: every prompt became a deny, so the
        # attachment stream holds nothing but the defers. Before the recovery
        # this reported 0% friction.
        use1, res1 = _deny_record("toolu_1", "sleep 300")
        use2, att2 = _decision_record("toolu_2", "gh run view 456", "")
        root = write_transcript([use1, res1, use2, att2])

        data = json.loads(self._run(root, "--json"))
        self.assertEqual(data["total"], 2)
        self.assertEqual(data["decisions"]["deny"], 1)
        self.assertEqual(data["categories"]["loop-sleep"], 1)

        out = self._run(root)
        self.assertIn("deny 1", out)
        self.assertIn("friction (ask+deny): 1 — 50.0% of the 2 Bash calls", out)
        self.assertIn("loop-sleep", out)
        self.assertIn("sleep 300", out)
        # The caveat belongs to the cross-guard view only.
        self.assertNotIn("tool-result text", out)

    def test_plugin_all_states_the_recovery_limit(self):
        use, res = _deny_record("toolu_1", "sleep 300")
        root = write_transcript([use, res])
        self.assertIn("tool-result text", self._run(root, "--plugin", "all"))

    def test_friction_rate_falls_when_the_guard_stays_quiet(self):
        # The issue #27 regression: before the denominator moved to Bash calls
        # this read 100%, and went on reading 100% however quiet the guard got.
        use, att = _decision_record(
            "toolu_1", "gh run watch 456", _stdout("ask", REASON_WATCH))
        quiet = [_bash_call("toolu_q%d" % i, "git status") for i in range(9)]
        root = write_transcripts([[use, att] + quiet])

        out = self._run(root)
        self.assertIn("friction (ask+deny): 1 — 10.0% of the 10 Bash calls", out)
        self.assertIn("sessions with a prompt: 1 of 1", out)

        data = json.loads(self._run(root, "--json"))
        self.assertEqual(data["total"], 1)          # decision records, as before
        self.assertEqual(data["bash_calls"], 10)
        self.assertEqual(data["sessions"], 1)
        self.assertEqual(data["sessions_prompted"], 1)

    def test_plugin_all_reports_a_sibling_that_stopped_running(self):
        # The blast radius of issue #29: under --plugin all a sibling whose hook
        # crashed on every call was reported as `defer`, reading as a guard that
        # looked and allowed rather than one that was never consulted.
        use1, att1 = _crashed_record("toolu_1", "git status",
                                     'python3 "/x/bash-pipe-guard.py"')
        use2, att2 = _decision_record(
            "toolu_2", "gh run watch 456", _stdout("ask", REASON_WATCH))
        root = write_transcript([use1, att1, use2, att2])

        data = json.loads(self._run(root, "--plugin", "all", "--json"))
        self.assertEqual(data["decisions"]["error"], 1)
        self.assertNotIn("defer", data["decisions"])
        self.assertEqual(
            data["hook_errors"],
            [["pipe-guard: hook_non_blocking_error: exit 126: Failed with "
              "non-blocking status code: /bin/sh: /x/scripts/"
              "run-python-hook.cmd: Permission denied", 1]])

        out = self._run(root, "--plugin", "all")
        self.assertIn("Hook failures", out)
        self.assertIn("pipe-guard: hook_non_blocking_error: exit 126", out)
        # The crash is not friction: it neither prompted nor let the guard look.
        self.assertIn("friction (ask+deny): 1 — 50.0% of the 2 Bash calls", out)

    def test_no_transcripts_errors(self):
        empty = tempfile.mkdtemp(prefix="fg-guard-friction-empty-")
        r = subprocess.run(
            [sys.executable, str(SCRIPT), "--transcripts", empty],
            capture_output=True, text=True, timeout=30)
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("No transcripts", r.stderr)


