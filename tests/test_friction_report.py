#!/usr/bin/env python3
"""Tests for scripts/friction-report.py.

Run with: python3 -m unittest discover tests
     or:  python3 tests/test_friction_report.py

The friction report is a read-only analyzer over the decisions Claude Code
persists in ~/.claude/projects/**/*.jsonl. These tests build synthetic
transcript files (attachment records + matching Bash tool_use blocks) and assert
the report's categorization, target extraction, and joins — never touching a real
transcript.

Signature fidelity: the reason fixtures are generated by calling
bash-foreground-guard.py's own finding builders (not hand-copied strings), so a
change to the guard's wording that broke a category regex fails these tests
instead of silently mis-bucketing real prompts.

Fixture rule (same as test_foreground_guard.py): synthetic commands only.
"""
import datetime as dt
import io
import json
import os
import subprocess
import sys
import tempfile
import unittest
from contextlib import redirect_stdout
from importlib import util
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SCRIPT = REPO / "scripts" / "friction-report.py"
GUARD = REPO / "scripts" / "bash-foreground-guard.py"

# Filenames have dashes, so import by path.
_spec = util.spec_from_file_location("friction_report", SCRIPT)
fr = util.module_from_spec(_spec)
_spec.loader.exec_module(fr)

_gspec = util.spec_from_file_location("foreground_guard", GUARD)
guard = util.module_from_spec(_gspec)
_gspec.loader.exec_module(guard)


# Real reason strings, generated by the guard's own finding builders — one per
# category. Minimal cfg: the builders read only the action keys and hint.
_CFG = {'poll_action': 'ask', 'slow_action': 'ask', 'hint': ''}
REASON_WATCH = guard.finding_watch(
    _CFG, "gh run watch 456", "gh run watch",
    "check once with `gh run view <run-id>`")[1]
REASON_LOOP = guard.finding_loop(_CFG)[1]
REASON_SANDWICH = guard.finding_sandwich(_CFG)[1]
REASON_SLEEP = guard.finding_sleep(_CFG, 300)[1]
REASON_SLOW = guard.finding_slow(
    _CFG, 'the slow-command pattern `make test-race\\b`', 600000, 120000,
    False)[1]
REASON_SLOW_TARGET = guard.finding_slow(
    _CFG, 'the slow-command target `make e2e*`', 1800000, 120000, False)[1]
# The same Class A findings for a `run_in_background: true` call: different
# wording, same categories.
_BG_CFG = dict(_CFG, backgrounded=True)
REASON_BG_WATCH = guard.finding_watch(
    _BG_CFG, "gh run watch 456", "gh run watch",
    "check once with `gh run view <run-id>`")[1]
REASON_BG_LOOP = guard.finding_loop(_BG_CFG)[1]
REASON_BG_SANDWICH = guard.finding_sandwich(_BG_CFG)[1]
REASON_BG_SLEEP = guard.finding_sleep(_BG_CFG, 300)[1]
# The deny->ask override prefix the hook prepends (see bash-foreground-guard.py
# main()); the underlying category must survive it.
REASON_OVERRIDE = ('foreground-guard override acknowledged '
                   '(FOREGROUND_GUARD_OVERRIDE is set) — downgraded from deny '
                   'to a confirmation prompt. ' + REASON_WATCH)
# A sibling guard's override prefix: identical phrasing apart from the guard
# name. In scope under --plugin all, and never a foreground-guard override.
REASON_SIBLING_OVERRIDE = ('prod-guard override acknowledged '
                           '(PROD_GUARD_OVERRIDE is set) — downgraded from deny '
                           'to a confirmation prompt. prod-guard: matches a '
                           'production pattern')


# What a deny actually looks like in a transcript. Claude Code writes no
# attachment for it (issue #25) — the reason reaches the transcript only as the
# error tool result handed back to the agent, so the fixture carries the guard's
# real deny wording: the reason plus the tail main() appends to a deny.
REASON_DENY = REASON_LOOP + " " + guard.deny_tail("auto")


def _deny_record(tooluseid, command, reason=REASON_DENY, cwd="/home/u/proj",
                 ts=None, is_error=True, as_blocks=False):
    """The two records a denied Bash call leaves: the assistant's tool_use and
    the error tool_result carrying the guard's reason. No attachment record —
    that is the bug this recovery exists for."""
    content = ([{"type": "text", "text": reason}] if as_blocks else reason)
    use = {
        "timestamp": ts or "2026-07-01T12:00:00Z",
        "cwd": cwd,
        "message": {"content": [
            {"type": "tool_use", "name": "Bash", "id": tooluseid,
             "input": {"command": command}}]},
    }
    result = {
        "timestamp": ts or "2026-07-01T12:00:00Z",
        "cwd": cwd,
        "message": {"content": [
            {"type": "tool_result", "tool_use_id": tooluseid,
             "is_error": is_error, "content": content}]},
    }
    return use, result


def _decision_record(tooluseid, command, stdout, cwd="/home/u/proj", ts=None,
                     hook_cmd='python3 "/x/scripts/bash-foreground-guard.py"',
                     **att_extra):
    """A transcript attachment record for one hook decision, plus the assistant
    tool_use record that command is joined from. Both carry cwd and timestamp,
    as real records do — the tool_use records are the report's denominator, so
    they meet the same scope filters.

    `type` is `hook_success` unless overridden: every real attachment carries
    one, and only that value means the hook produced a verdict (issue #29)."""
    att = {
        "type": "hook_success",
        "hookName": "PreToolUse:Bash",
        "command": hook_cmd,
        "toolUseID": tooluseid,
        "stdout": stdout,
        "stderr": "",
        "exitCode": 0,
    }
    att.update(att_extra)
    att = {
        "timestamp": ts or "2026-07-01T12:00:00Z",
        "cwd": cwd,
        "attachment": att,
    }
    use = {
        "timestamp": ts or "2026-07-01T12:00:00Z",
        "cwd": cwd,
        "message": {"content": [
            {"type": "tool_use", "name": "Bash", "id": tooluseid,
             "input": {"command": command}}]},
    }
    return use, att


def _crashed_record(tooluseid, command, hook_cmd, **kw):
    """A hook that never ran: Claude Code writes the attachment anyway, with an
    empty stdout, a non-zero exitCode and the failure on stderr. Shape taken
    from the 5,472 real ones behind issue #29 (exit 126, hook script left
    non-executable)."""
    return _decision_record(
        tooluseid, command, "", hook_cmd=hook_cmd,
        type="hook_non_blocking_error", exitCode=126,
        stderr=("Failed with non-blocking status code: /bin/sh: "
                "/x/scripts/run-python-hook.cmd: Permission denied"), **kw)


def _bash_call(tooluseid, command, cwd="/home/u/proj", ts=None):
    """A Bash call the guard deferred on: the tool_use record and nothing else.
    A silent defer writes no attachment (issue #27), so this is the only trace
    such a call leaves — and the whole reason the denominator counts calls."""
    return {
        "timestamp": ts or "2026-07-01T12:00:00Z",
        "cwd": cwd,
        "message": {"content": [
            {"type": "tool_use", "name": "Bash", "id": tooluseid,
             "input": {"command": command}}]},
    }


def _stdout(decision, reason):
    return json.dumps({"hookSpecificOutput": {
        "hookEventName": "PreToolUse",
        "permissionDecision": decision,
        "permissionDecisionReason": reason}})


def write_transcripts(sessions):
    """Write each session (a list of records) as its own .jsonl transcript in a
    fresh temp dir; return the transcript root."""
    root = tempfile.mkdtemp(prefix="fg-guard-friction-")
    proj = os.path.join(root, "-home-u-proj")
    os.makedirs(proj)
    for i, records in enumerate(sessions):
        path = os.path.join(proj, "session%d.jsonl" % i)
        with open(path, "w", encoding="utf-8") as f:
            for rec in records:
                f.write(json.dumps(rec) + "\n")
    return root


def write_transcript(lines):
    """One session's worth of records; see write_transcripts."""
    return write_transcripts([lines])


